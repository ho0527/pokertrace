	# 支援：?userid=（依使用者過濾）、?keyword=（比對使用者姓名/信箱/玩家編號、API 路徑、方法、IP）、?erroronly=1（只列狀態碼非 200 的紀錄）、?page=、?limit=（分頁，避免一次撈太多筆）。
