	token=None
	try:
		if header:
			token=header.split("Bearer ")[1]
	except Exception as error:
		return errorresponse("ERROR_token_not_found")
	if not token:
		return errorresponse("ERROR_token_not_found")
	tokenrow=query(SETTING["dbname"],f"""SELECT*FROM "token" WHERE "token"=%s""",[token],SETTING["dbsetting"])
