def sessionaccess(sessionrow,userrow):
	access={
		"isown": False,
		"isstaff": False,
		"isadmin": False,
		"isplayer": False,
		"accessrole": "",
		"canrecord": False,
		"canunifiedrecord": False,
		"cantimer": False
	}
	if not sessionrow or not userrow:
		return access
	if intval(userrow.get("permission"))>=4:
		access["isadmin"]=True
		access["accessrole"]="admin"
	if sessionrow["userid"]==userrow["id"]:
		access["isown"]=True
		access["accessrole"]="owner"
	staffrow=query(SETTING["dbname"],"""SELECT*FROM "sessionstaff" WHERE "sessionid"=%s AND "staffuserid"=%s AND "status"='active' AND "deletetime" IS NULL""",[sessionrow["id"],userrow["id"]],SETTING["dbsetting"])
	if not staffrow:
		staffrow=query(SETTING["dbname"],"""SELECT*FROM "userstaff" WHERE "userid"=%s AND "staffuserid"=%s AND "status"='active' AND "deletetime" IS NULL""",[sessionrow["userid"],userrow["id"]],SETTING["dbsetting"])
	if staffrow:
		access["isstaff"]=True
		access["accessrole"]=staffrow[0]["role"]
	playerrow=query(SETTING["dbname"],"""SELECT*FROM "sessionplayer" WHERE "sessionid"=%s AND "userid"=%s AND "status"='confirmed' AND "deletetime" IS NULL""",[sessionrow["id"],userrow["id"]],SETTING["dbsetting"])
	if playerrow:
		access["isplayer"]=True
	if access["isown"] or access["isadmin"]:
		access["canrecord"]=True
		access["canunifiedrecord"]=True
	if boolval(sessionrow.get("unifiedhandrecord")):
		if access["accessrole"]=="dealer" or access["accessrole"]=="floor" or access["accessrole"]=="assistant":
			access["canrecord"]=True
			access["canunifiedrecord"]=True
	else:
		if access["isplayer"] or access["isown"] or access["isadmin"]:
			access["canrecord"]=True
	if access["isown"] or access["isadmin"] or access["accessrole"]=="floor" or access["accessrole"]=="assistant":
		access["cantimer"]=True
	return access


