def solvehandwinner(request):
	userrow,errresp=getrequestuser(request)
	if errresp:
		return errresp
	try:
		data=json.loads(request.body)
	except Exception as error:
		return errorresponse("ERROR_request_data_not_found")
	try:
		board=[]
		boardraw=boardcardsfromdata(data.get("boardcard") or {})
		for i in range(len(boardraw)):
			board.append(eval7.Card(boardraw[i]))
		if len(board)<3:
			return Response({"success": True,"data": {"winners": [],"results": [],"message": "BOARD_NOT_ENOUGH"}},status.HTTP_200_OK)
		seats=[]
		selfseat=intval(data.get("selfseating"),0)
		herocards=cardlistfrompair(data.get("handcard") or {})
		if selfseat and len(herocards)==2:
			seats.append({
				"seat": selfseat,
				"cards": herocards
			})
		showdowndata=data.get("showdowndata") or {}
		for key in showdowndata:
			row=showdowndata[key]
			if boolval(row.get("shown")):
				cards=cardlistfrompair(row)
				if len(cards)==2:
					seatno=intval(key,0)
					existed=False
					for i in range(len(seats)):
						if seats[i]["seat"]==seatno:
							seats[i]["cards"]=cards
							existed=True
					if not existed:
						seats.append({
							"seat": seatno,
							"cards": cards
						})
		results=[]
		bestscore=None
		for i in range(len(seats)):
			handcards=[eval7.Card(seats[i]["cards"][0]),eval7.Card(seats[i]["cards"][1])]
			score=eval7.evaluate(handcards+board)
			results.append({
				"seat": seats[i]["seat"],
				"score": score,
				"cards": seats[i]["cards"]
			})
			if bestscore is None or score>bestscore:
				bestscore=score
		winners=[]
		for i in range(len(results)):
			if results[i]["score"]==bestscore:
				winners.append(results[i]["seat"])
		return Response({"success": True,"data": {"winners": winners,"results": results}},status.HTTP_200_OK)
	except Exception as error:
		return errorresponse("ERROR_request_data_type_error")


