def advancehandcount(sessionrow):
	try:
		from .timer import buildtimerstate,savesplitstate,broadcasttimerupdate,boolval as timerbool,intval as timerint
		state=buildtimerstate(sessionrow["id"])
		if not state:
			return {}
		index=timerint(state.get("currentIndex"),0)
		schedule=state.get("schedule") or []
		if index>=len(schedule):
			return state
		item=schedule[index]
		count=timerint(item.get("handCount"),0)+1
		item["handCount"]=count
		state["schedule"][index]=item
		if item.get("timemode")=="handcount":
			target=timerint(item.get("handTargetCount"),0)
			if 0<target and count>=target and index<len(schedule)-1:
				state["currentIndex"]=index+1
				state["secondsLeft"]=timerint(schedule[index+1].get("dur"),20)*60
				state["running"]=False
		savesplitstate(sessionrow,state)
		state=buildtimerstate(sessionrow["id"])
		broadcasttimerupdate(sessionrow["id"],state)
		return state
	except Exception as error:
		printcolorhaveline("fail","[ERROR] advancehandcount "+str(error),"")
		return {}


