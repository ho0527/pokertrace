def canreadsessionhands(sessionrow,userrow,access):
	if access["canrecord"] or access["isplayer"] or access["isstaff"] or access["isown"] or access["isadmin"]:
		return True
	if sessionregistered(sessionrow["id"],userrow["id"]):
		return True
	if boolval(sessionrow.get("owned")) and boolval(sessionrow.get("linkuser")) and not boolval(sessionrow.get("private")):
		return True
	return False


