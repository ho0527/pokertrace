def serializehand(hand,withdetail=True,seatingrow=None,bittingrow=None):
	item=dict(hand)
	item["handcard"]=jsonval(item.get("handcard"),{})
	item["boardcard"]=jsonval(item.get("boardcard"),{})
	item["actionsjson"]=jsonval(item.get("actionsjson"),{})
	item["adjustments"]=jsonval(item.get("adjustmentsjson"),{})
	item["familydata"]=jsonval(item.get("familydatajson"),{})
	item["recordtype"]=item.get("recordtype") or "hand"
	item["exceptiontype"]=item.get("exceptiontype") or ""
	item["createtime"]=handtime(item.get("createtime"))
	item["updatetime"]=handtime(item.get("updatetime"))
	item["handtime"]=handtime(item.get("handtime"))
	if withdetail:
		if seatingrow is None:
			seatingrow=query(SETTING["dbname"],"""SELECT*FROM "handseating" WHERE "handid"=%s AND "deletetime" IS NULL ORDER BY "seatno" ASC""",[hand["id"]],SETTING["dbsetting"])
		if bittingrow is None:
			bittingrow=query(SETTING["dbname"],"""SELECT*FROM "handbittingdata" WHERE "handid"=%s AND "deletetime" IS NULL ORDER BY "id" ASC""",[hand["id"]],SETTING["dbsetting"])
		item["seatingdata"]=serializeseating(seatingrow)
		item["bittingdata"]=serializebitting(bittingrow)
		invest={}
		for i in range(len(item["bittingdata"])):
			seatno=intval(item["bittingdata"][i].get("seatno"))
			if seatno not in invest:
				invest[seatno]=0
			invest[seatno]=invest[seatno]+intval(item["bittingdata"][i].get("chip"))
		hero=None
		for i in range(len(item["seatingdata"])):
			if item["seatingdata"][i]["seatno"]==item.get("selfseating"):
				hero=item["seatingdata"][i]
		item["playername"]=hero["name"] if hero else ""
		item["result"]=0
		if hero:
			if item["recordtype"]!="hand":
				# 校正 / 例外紀錄沒有下注，淨增減就是 endchip-chip（chipchange 在此不是投入額）
				item["result"]=intval(hero.get("endchip"))-intval(hero.get("chip"))
			else:
				oldinvest=intval(hero.get("chipchange"))
				currentinvest=intval(invest.get(hero["seatno"],oldinvest))
				winamount=0
				if boolval(hero.get("winnered")):
					winamount=intval(hero.get("endchip"))-intval(hero.get("chip"))+oldinvest
				item["result"]=winamount-currentinvest
	return item


def buildseatmap(sessionrow,tablerow,latesthand):
	maxseat=intval(sessionrow.get("maxseat"),9)
	seatmap=[None]
	for i in range(maxseat):
		seatmap.append(False)
	if boolval(sessionrow.get("linkuser")):
		row=query(SETTING["dbname"],"""
			SELECT sp."id" AS sessionplayerid,sp."userid",sp."seatno",sp."startchip",u."name"
			FROM "sessionplayer" sp
			JOIN "user" u ON u."id"=sp."userid"
			WHERE sp."sessionid"=%s AND sp."tableid"=%s AND sp."status"='confirmed' AND sp."seatno" IS NOT NULL AND sp."deletetime" IS NULL
			  AND NOT EXISTS(
				  SELECT 1 FROM "sessiontimerplayer" tp
				  WHERE tp."sessionid"=sp."sessionid" AND tp."sessionplayerid"=sp."id" AND tp."status"='eliminated' AND tp."deletetime" IS NULL
			  )
			ORDER BY sp."seatno" ASC
		""",[sessionrow["id"],tablerow["id"]],SETTING["dbsetting"])
		for item in row or []:
			seatno=intval(item["seatno"])
			if 0<seatno and seatno<len(seatmap):
				seatmap[seatno]={
					"chip": item.get("startchip") or sessionrow.get("chip") or 0,
					"unknownchip": intval(item.get("startchip"),0)<0,
					"name": item.get("name") or "",
					"userid": item.get("userid"),
					"sessionplayerid": item.get("sessionplayerid"),
					"banned": False
				}
	else:
		row=query(SETTING["dbname"],"""SELECT*FROM "seating" WHERE "tableid"=%s AND "deletetime" IS NULL ORDER BY "seatno" ASC,"time" ASC,"id" ASC""",[tablerow["id"]],SETTING["dbsetting"])
		for item in row or []:
			seatno=intval(item["seatno"])
			if 0<seatno and seatno<len(seatmap):
				if item["type"]=="leave":
					seatmap[seatno]=False
				else:
					seatmap[seatno]={
						"chip": item.get("chip") or sessionrow.get("chip") or 0,
						"unknownchip": intval(item.get("chip"),0)<0,
						"name": item.get("name") or "",
						"userid": item.get("userid"),
						"sessionplayerid": item.get("sessionplayerid"),
						"banned": False
					}
	if latesthand:
		seatingrow=query(SETTING["dbname"],"""SELECT*FROM "handseating" WHERE "handid"=%s AND "deletetime" IS NULL ORDER BY "seatno" ASC""",[latesthand["id"]],SETTING["dbsetting"])
		latestchips={}
		for item in seatingrow or []:
			chip=item.get("endchip") or item.get("chip") or 0
			if item.get("sessionplayerid"):
				latestchips["sp:"+str(item["sessionplayerid"])]=chip
			elif item.get("userid"):
				latestchips["u:"+str(item["userid"])]=chip
			elif item.get("name"):
				latestchips["n:"+str(item["name"])]=chip
		for seatno in range(1,len(seatmap)):
			item=seatmap[seatno]
			if not item:
				continue
			key=None
			if item.get("sessionplayerid"):
				key="sp:"+str(item["sessionplayerid"])
			elif item.get("userid"):
				key="u:"+str(item["userid"])
			elif item.get("name"):
				key="n:"+str(item["name"])
			if key and key in latestchips:
				item["chip"]=latestchips[key]
				item["unknownchip"]=intval(latestchips[key],0)<0
	return seatmap


def nextdealerseat(latesthand,seatmap,tablerow):
	if not latesthand:
		return intval(tablerow.get("firstdealerplace"),1)
	last=intval(latesthand.get("dealerseat"),1)
	maxseat=len(seatmap)-1
	for i in range(maxseat):
		last=last+1
		if last>maxseat:
			last=1
		if seatmap[last]:
			return last
	return 1


