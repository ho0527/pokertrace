#
# DM（Drawmaha / 坐馬哈）於 2026-08-10 加入，gametype 表同時補了 code='DM' 那一列。
#   5 張底牌，先換一次牌，再發 5 張公共牌，**底池拆兩半**：
#   一半給最好的五張抽牌牌型（只看自己那 5 張），一半給最好的奧馬哈牌型（恰 2 底牌 + 恰 3 公牌）。
