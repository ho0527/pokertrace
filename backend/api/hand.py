			# **「現在」要用 nowtime() 當參數傳進來, 不可以寫 SQL 的 now()。**
			# 全站慣例是把本地牆上時間存進 timestamptz 並原樣顯示
			# (前端 ptformatdatetime 不做時區換算), 而 SQL 的 now() 是真 UTC ——
