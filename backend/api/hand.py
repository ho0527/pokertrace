# ================= 勝率計算器每 IP 速率限制 =================
# equity 是公開勝率計算器工具頁（tool/equity.html）用的端點，不加登入限制以免破壞免登入公開功能，
# 改用模組層 in-memory 每 IP 速率限制防止匿名濫用：每 IP 每 EQUITYRATELIMITWINDOW 秒最多
# EQUITYRATELIMITMAX 次，超限回 429。帶有效 token 的登入使用者略過此限流。
# 取 IP 優先用 nginx 設的 X-Real-IP，取不到才 fallback REMOTE_ADDR；本部署兩者都是真實 client IP
# (uvicorn proxy_headers 預設開啟，已從 X-Forwarded-For 還原真實來源；nginx 也有 proxy_set_header
#  X-Real-IP $remote_addr 覆寫用戶端偽造值)，統一取法讓四處寫法一致。
EQUITYRATELIMITWINDOW=60
EQUITYRATELIMITMAX=12
EQUITYRATELIMITLOCK=threading.Lock()
equityratelimitrecord={}


def equityratelimited(request):
	"""回傳該請求來源 IP 是否已超過勝率計算速率限制；未超過時記下這一次。"""
	ip=request.META.get("HTTP_X_REAL_IP") or request.META.get("REMOTE_ADDR","")
	now=time.time()
	limited=False
	with EQUITYRATELIMITLOCK:
		# 順手清掉已全部過期的 IP 紀錄，避免 dict 無限成長
		for key in list(equityratelimitrecord.keys()):
			recentlist=[t for t in equityratelimitrecord[key] if now-t<EQUITYRATELIMITWINDOW]
			if recentlist:
				equityratelimitrecord[key]=recentlist
			else:
				del equityratelimitrecord[key]
		recentlist=equityratelimitrecord.get(ip,[])
		if len(recentlist)>=EQUITYRATELIMITMAX:
			limited=True
		else:
			recentlist.append(now)
			equityratelimitrecord[ip]=recentlist
	return limited


