def intval(value,defaultvalue=0):
	try:
		return int(value)
	except Exception as error:
		return defaultvalue


def jsonval(value,defaultvalue):
	if value is None:
		return defaultvalue
	if isinstance(value,dict) or isinstance(value,list):
		return value
	try:
		return json.loads(value)
	except Exception as error:
		return defaultvalue


def handtime(value):
	if not value:
		return None
	return str(value).replace("+00:00","").replace("T"," ")


