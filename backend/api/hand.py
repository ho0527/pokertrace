def normalizetimebankstate(stateval,defaultseconds=15):
	state={}
	if isinstance(stateval,str):
		try:
			state=json.loads(stateval)
		except Exception as error:
			state={}
	elif isinstance(stateval,dict):
		state=dict(stateval)
	state["enabled"]=boolval(state.get("enabled"))
	state["seatno"]=intval(state.get("seatno"),0)
	state["durationseconds"]=max(1,intval(state.get("durationseconds"),defaultseconds))
	state["remainingseconds"]=intval(state.get("remainingseconds"),state["durationseconds"])
	if state["remainingseconds"]<0:
		state["remainingseconds"]=0
	state["endtime"]=state.get("endtime") or ""
	state["running"]=boolval(state.get("running"))
	state["expired"]=boolval(state.get("expired"))
	state["startedby"]=intval(state.get("startedby"),0)
	state["starttime"]=state.get("starttime") or ""
	state["updatedtime"]=state.get("updatedtime") or nowtime()
	return state


